package service

import "fmt"

func deviceRejection(profile string, code byte) *Error {
	description := commonDeviceErrorDescriptions[code]
	if description == "" {
		if profile == "ffd1.2" {
			description = ffd12DeviceErrorDescriptions[code]
		} else {
			description = baseDeviceErrorDescriptions[code]
		}
	}
	message := fmt.Sprintf("Неизвестный код ошибки ККТ 0x%02X", code)
	if description != "" {
		message = fmt.Sprintf("Ошибка ККТ 0x%02X. %s", code, description)
	}
	return &Error{Code: "device_error", Message: message, DeviceCode: &code}
}

